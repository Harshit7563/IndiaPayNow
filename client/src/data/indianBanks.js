export function findBankByName(name = '') {
  const q = name.trim().toLowerCase();
  if (!q) return null;
  return (
    indianBanks.find((b) => b.name.toLowerCase() === q) ||
    indianBanks.find((b) => b.shortName.toLowerCase() === q) ||
    indianBanks.find((b) => b.name.toLowerCase().includes(q))
  );
}

export function findBankByIfsc(ifsc = '') {
  const prefix = String(ifsc).slice(0, 4).toUpperCase();
  if (prefix.length < 4) return null;
  return indianBanks.find((b) => b.ifscPrefix === prefix) || null;
}
